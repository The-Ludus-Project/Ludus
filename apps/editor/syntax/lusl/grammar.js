// Thanks to the Tree-sitter contributors, "The Grammar DSL" and "Writing the Grammar":
// https://tree-sitter.github.io/tree-sitter/creating-parsers/. This grammar supplies
// recoverable editor structure. The LUSL compiler owns language acceptance.
const COMPARISON = 7;
const UNARY = 13;
const POSTFIX = 14;
const KEYWORDS = [
  "break", "case", "class", "concept", "const", "continue", "default", "discard", "do",
  "dynamic", "else", "enum", "extension", "extern", "false", "for", "goto", "groupshared",
  "if", "in", "inout", "interface", "out", "requires", "return", "static", "static_assert",
  "struct", "switch", "template", "true", "typedef", "typename", "union", "void", "while",
  "sizeof", "constexpr", "uniform",
];

function separated(rule, separator) {
  return seq(rule, repeat(seq(separator, rule)));
}

module.exports = grammar({
  name: "lusl",
  word: $ => $.identifier,
  extras: $ => [/\s/, $.comment, $.preproc_directive],
  conflicts: $ => [
    [$.type_identifier, $._expression, $.template_reference],
    [$._expression, $.template_reference],
    [$.attribute_declaration, $._expression],
    [$.compound_statement, $.initializer_list],
    [$.type_reference, $._expression],
  ],

  rules: {
    translation_unit: $ => repeat($._declaration),
    _declaration: $ => choice($.function_definition, $.function_declaration, $.declaration,
      $.struct_specifier, $.interface_specifier, $.extension_declaration, $.enum_specifier,
      $.extern_declaration, $.template_declaration, $.concept_definition, $.static_assert_declaration,
      $.type_definition),

    identifier: _ => /[A-Za-z_][A-Za-z0-9_]*/,
    comment: _ => token(choice(seq("//", /[^\n]*/), /\/\*[^*]*\*+([^/*][^*]*\*+)*\//)),
    preproc_directive: _ => token(seq("#", /[ \t]*[a-zA-Z_][^\n]*/)),
    number_literal: _ => token(/(0[xX][0-9a-fA-F]+|([0-9]+(\.[0-9]*)?|\.[0-9]+)([eE][+-]?[0-9]+)?)[uUhHfFlL]*/),
    string_literal: $ => seq('"', repeat(choice(token.immediate(/[^"\\\n]+/), $.escape_sequence)), '"'),
    escape_sequence: _ => token.immediate(/\\[^\n]/),
    // Reserved syntax remains recognizable while a user is entering it.
    reserved_keyword: _ => choice(...KEYWORDS.filter(word => ["class", "goto", "union"].includes(word))),
    primitive_type: _ => choice("void",
      token(/(bool|int16|int32|int64|uint16|uint32|uint64|float16|float32|float64)(x[234](x[234])?)?/),
      token(/(float|int|uint|half|double)([234](x[234])?)?/)),
    type_identifier: $ => alias($.identifier, $.type_name),
    type_reference: $ => seq(choice($.primitive_type, $.type_identifier), optional($.generic_arguments)),
    generic_arguments: $ => prec.dynamic(-1, seq("<", separated(choice($.type_reference, $.number_literal), ","), ">")),
    _modifier: _ => choice("const", "static", "constexpr", "groupshared", "uniform", "dynamic", "in", "out", "inout"),
    attribute_declaration: $ => choice(
      seq("[", choice("space", $.identifier), optional($.argument_list), "]"),
      seq("[[", $.identifier, optional($.argument_list), "]]")),
    array_declarator: $ => seq("[", $._expression, "]"),
    parameter_declaration: $ => seq(repeat($._modifier), field("type", $.type_reference),
      field("name", $.identifier), repeat($.array_declarator), optional(seq(":", $.identifier)), optional(seq("=", $._expression))),
    parameter_list: $ => seq("(", optional(separated($.parameter_declaration, ",")), ")"),
    function_declarator: $ => seq(field("name", $.identifier), $.parameter_list, optional(seq(":", $.identifier))),
    function_definition: $ => seq(repeat($.attribute_declaration), repeat($._modifier), field("type", $.type_reference),
      field("declarator", $.function_declarator), field("body", $.compound_statement)),
    function_declaration: $ => seq(repeat($.attribute_declaration), repeat($._modifier), field("type", $.type_reference),
      field("declarator", $.function_declarator), ";"),
    _variable_declaration: $ => seq(repeat($._modifier), field("type", $.type_reference),
      field("name", $.identifier), repeat($.array_declarator), optional(seq(":", $.identifier)), optional(seq("=", $._expression))),
    declaration: $ => seq(repeat($.attribute_declaration), $._variable_declaration, ";"),

    _bases: $ => seq(":", separated($.type_reference, ",")),
    field_declaration_list: $ => seq("{", repeat($._declaration), "}"),
    struct_specifier: $ => seq("struct", field("name", $.type_identifier), optional($._bases),
      field("body", $.field_declaration_list), ";"),
    interface_specifier: $ => seq("interface", field("name", $.type_identifier), optional($._bases),
      field("body", $.field_declaration_list), ";"),
    extension_declaration: $ => seq("extension", field("name", $.type_identifier), $._bases,
      field("body", $.field_declaration_list), optional(";")),
    enum_specifier: $ => seq("enum", optional("class"), field("name", $.type_identifier),
      optional(seq(":", $.type_reference)), $.enumerator_list, ";"),
    enumerator_list: $ => seq("{", optional(seq(separated($.enumerator, ","), optional(","))), "}"),
    enumerator: $ => seq(field("name", $.identifier), optional(seq("=", $._expression))),
    extern_declaration: $ => seq("extern", "slang", optional($.string_literal),
      field("body", $.field_declaration_list), optional(";")),
    type_definition: $ => seq("typedef", $.type_reference, field("name", $.type_identifier), ";"),
    template_declaration: $ => seq("template", $.template_parameter_list, optional(seq("requires", $._expression)),
      field("declaration", choice($.function_definition, $.function_declaration, $.struct_specifier))),
    template_parameter_list: $ => seq("<", separated($.template_parameter, ","), ">"),
    template_parameter: $ => seq(choice("typename", $.type_reference), field("name", $.identifier)),
    concept_definition: $ => seq("concept", field("name", $.type_identifier), "<",
      separated($.identifier, ","), ">", "=", $._expression, ";"),
    static_assert_declaration: $ => seq("static_assert", $.argument_list, ";"),

    compound_statement: $ => seq("{", repeat($._statement), "}"),
    _statement: $ => choice($.compound_statement, $.declaration, $.if_statement, $.for_statement,
      $.while_statement, $.do_statement, $.switch_statement, $.return_statement, $.jump_statement,
      $.expression_statement, $.static_assert_declaration),
    if_statement: $ => prec.right(seq("if", optional("constexpr"), $.parenthesized_expression, $._statement,
      optional(seq("else", $._statement)))),
    for_statement: $ => seq("for", "(", optional(choice($._variable_declaration, $._effect)), ";",
      optional($._expression), ";", optional($._effect), ")", $._statement),
    while_statement: $ => seq("while", $.parenthesized_expression, $._statement),
    do_statement: $ => seq("do", $._statement, "while", $.parenthesized_expression, ";"),
    switch_statement: $ => seq("switch", $.parenthesized_expression, "{", repeat($.case_statement), "}"),
    case_statement: $ => prec.right(seq(choice(seq("case", $._expression), "default"), ":", repeat($._statement))),
    return_statement: $ => seq("return", optional($._expression), ";"),
    jump_statement: $ => seq(choice("break", "continue", "discard", $.attribute_declaration, $.reserved_keyword), ";"),
    expression_statement: $ => seq(optional($._effect), ";"),
    _effect: $ => choice($._expression, $.assignment_expression, $.update_expression),
    assignment_expression: $ => prec.right(seq($._expression,
      choice("=", "+=", "-=", "*=", "/=", "%=", "&=", "|=", "^=", "<<=", ">>="), $._expression)),
    update_expression: $ => choice(seq(choice("++", "--"), $._expression), seq($._expression, choice("++", "--"))),

    _expression: $ => choice($.identifier, $.number_literal, $.string_literal, $.boolean_literal, $.primitive_type,
      $.parenthesized_expression, $.initializer_list, $.call_expression, $.subscript_expression,
      $.conformance_expression, $.field_expression, $.qualified_identifier, $.template_reference, $.unary_expression, $.binary_expression, $.conditional_expression),
    boolean_literal: _ => choice("true", "false"),
    parenthesized_expression: $ => seq("(", $._expression, ")"),
    initializer_list: $ => seq("{", optional(seq(separated($.initializer_pair, ","), optional(","))), "}"),
    initializer_pair: $ => seq(".", field("name", $.identifier), "=", field("value", $._expression)),
    argument_list: $ => seq("(", optional(separated($.argument, ",")), ")"),
    argument: $ => seq(optional(seq(field("name", $.identifier), "=")), optional(choice("out", "inout")), $._expression),
    call_expression: $ => prec(POSTFIX, seq(field("function", $._expression), $.argument_list)),
    subscript_expression: $ => prec(POSTFIX, seq($._expression, "[", $._expression, "]")),
    field_expression: $ => prec(POSTFIX, seq($._expression, ".", field("field", alias($.identifier, $.field_identifier)))),
    template_reference: $ => prec.dynamic(2, seq($.identifier, $.generic_arguments)),
    qualified_identifier: $ => prec(POSTFIX, seq($._expression, "::", $.identifier)),
    unary_expression: $ => prec(UNARY, seq(choice("+", "-", "!", "~", "sizeof"), $._expression)),
    conditional_expression: $ => prec.right(1, seq($._expression, "?", $._expression, ":", $._expression)),
    binary_expression: $ => choice(...[
      [2, "||"], [3, "&&"], [4, "|"], [5, "^"], [6, "&"],
      [COMPARISON, choice("==", "!=")], [8, choice("<", "<=", ">", ">=")],
      [9, choice("<<", ">>")], [10, choice("+", "-")], [11, choice("*", "/", "%")],
    ].map(([priority, operator]) => prec.left(priority, seq($._expression, operator, $._expression)))),
    conformance_expression: $ => seq("(", $.type_reference, ":", $.type_reference, ")"),
  },
});
