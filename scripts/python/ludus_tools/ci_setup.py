"""Explicit, no-overwrite GitHub Actions build/test setup for projects.

``ludus project ci init`` adds ``.github/workflows/ci.yml`` to an existing
project, and ``ludus project create --ci github`` stages the same files with a
new project. The workflow builds the platform's Release profile and runs the
project's CTest tests against the digest-pinned Release SDK that the release
workflow also uses. It has read-only repository permissions and no secrets.

GitHub reads workflows only from the repository root, so a project nested
inside another Git work tree is refused rather than given a workflow that
never runs. Project repository detection reads the file system; it never runs
Git in the project or contacts a remote.
"""
from __future__ import annotations

import os
import re
import subprocess
import tempfile
from pathlib import Path
from typing import Optional, Sequence, Union

from . import descriptor, operations, workflow_steps
from .errors import CONFLICT, INVALID_PROJECT, ToolingError
from .templates import TemplateFile

CI_PROVIDERS = ("github",)
WORKFLOW_RELPATH = ".github/workflows/ci.yml"
# The build/test job's pinned host tools live in this runner-local virtual environment.
CI_TOOLS_VENV = "/tmp/ludus-ci-tools"
_TOOLS_REF_RE = re.compile(r"[a-f0-9]{40}")

WORKFLOW = r'''name: Ludus CI
# Generated by `ludus project ci init`. This file is yours: edit triggers,
# branches and steps as the project grows. Rerunning setup never overwrites it.
on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: ludus-ci-${{ github.ref }}
  cancel-in-progress: true
jobs:
  # Without a hosted Release SDK there is nothing to build against. Report that
  # on a short job instead of provisioning the toolchain or failing every push.
  sdk-not-configured:
    if: NOT_CONFIGURED_TOKEN
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    steps:
NOTICE_STEPS_TOKENBUILD_JOBS_TOKEN'''

NOTICE_STEP = '''      - name: Report missing SDK configuration
        run: echo "::notice title=Ludus SDK not configured::Set repository variables URL_VAR_TOKEN and SHA_VAR_TOKEN to build and test in CI."
'''

PLATFORM_NOTICE_STEP = '''      - name: Report missing PLATFORM_TOKEN SDK configuration
        if: UNSET_TOKEN
        run: echo "::notice title=Ludus SDK not configured::Set repository variables URL_VAR_TOKEN and SHA_VAR_TOKEN to build and test on PLATFORM_TOKEN."
'''

BUILD_JOB = r'''  JOB_TOKEN:
    if: SET_TOKEN
    runs-on: RUNNER_TOKEN
    timeout-minutes: 60
    steps:
CHECKOUT_TOKEN      - name: Install build prerequisites
        run: |
BUILD_PREREQUISITES_TOKENSDK_STEP_TOKEN      - name: Build PROFILE_TOKEN
BUILD_ENV_TOKEN        run: ludus project build . --profile PROFILE_TOKEN --sdk "$LUDUS_RELEASE_SDK_PREFIX"
      - name: Run tests
        run: ctest --test-dir out/build/PROFILE_TOKEN --output-on-failure --timeout 300
'''


def sdk_variables(platform: str, platforms: Sequence[str]) -> tuple[str, str]:
    """Return the repository variables naming ``platform``'s Release SDK URL and SHA-256.

    A single-platform workflow uses the unsuffixed names shared with the release
    workflow; a multi-platform workflow suffixes each name with its platform,
    such as ``LUDUS_RELEASE_SDK_URL_MACOS_ARM64``.
    """
    names = ("LUDUS_RELEASE_SDK_URL", "LUDUS_RELEASE_SDK_SHA256")
    if len(platforms) == 1:
        return names
    suffix = "_" + platform.upper().replace("-", "_")
    return names[0] + suffix, names[1] + suffix


def select_platforms(platforms: Sequence[str]) -> tuple[str, ...]:
    """Return the requested native CI platforms without duplicates, in ``NATIVE_PLATFORMS`` order."""
    for platform in platforms:
        if platform not in workflow_steps.NATIVE_PLATFORMS:
            raise ToolingError(INVALID_PROJECT, f"unsupported CI platform {platform!r}")
        workflow_steps.require_hosted_toolchain(platform)
    selected = tuple(platform for platform in workflow_steps.NATIVE_PLATFORMS if platform in platforms)
    if len(selected) == 0:
        raise ToolingError(INVALID_PROJECT, "CI setup requires at least one platform")
    return selected


def _build_job(platform: str, platforms: Sequence[str]) -> str:
    url, sha = sdk_variables(platform, platforms)
    job = "build-and-test" if len(platforms) == 1 else "build-and-test-" + platform
    profile = ("macos" if platform.startswith("macos-") else "linux") + "-clang-release"
    # Ubuntu installs only the versioned compiler name; name it for the
    # backend's host-toolchain check. macOS puts Homebrew LLVM first on PATH.
    build_env = "" if platform.startswith("macos-") else (
        "        env:\n          CXX: " + workflow_steps.pinned_compiler() + "\n")
    return (BUILD_JOB.replace("JOB_TOKEN", job)
            .replace("SET_TOKEN", f"vars.{url} != '' || vars.{sha} != ''")
            .replace("RUNNER_TOKEN", workflow_steps.runner_for(platform))
            .replace("CHECKOUT_TOKEN", workflow_steps.CHECKOUT_STEP)
            .replace("BUILD_PREREQUISITES_TOKEN", workflow_steps.build_prerequisites(platform, CI_TOOLS_VENV))
            .replace("SDK_STEP_TOKEN", workflow_steps.release_sdk_step(
                "Acquire digest-pinned Release SDK",
                f"Set both {url} (HTTPS) and {sha} (lowercase SHA-256)", url_variable=url, sha_variable=sha))
            .replace("BUILD_ENV_TOKEN", build_env)
            .replace("PROFILE_TOKEN", profile))


def _unset_condition(platform: str, platforms: Sequence[str]) -> str:
    return "vars.{0} == '' && vars.{1} == ''".format(*sdk_variables(platform, platforms))


def _notice_step(platform: str, platforms: Sequence[str]) -> str:
    url, sha = sdk_variables(platform, platforms)
    step = NOTICE_STEP if len(platforms) == 1 else PLATFORM_NOTICE_STEP
    return (step.replace("UNSET_TOKEN", _unset_condition(platform, platforms)).replace("PLATFORM_TOKEN", platform)
            .replace("URL_VAR_TOKEN", url).replace("SHA_VAR_TOKEN", sha))


def workflow_text(*platforms: str) -> str:
    """Return the build/test workflow for native platforms (``linux-x64``, ``macos-arm64``).

    Each platform gets its own build job, skipped while its SDK variables are unset.
    """
    platforms = select_platforms(platforms)
    if len(platforms) == 1:
        not_configured = _unset_condition(platforms[0], platforms)
    else:
        not_configured = " || ".join(f"({_unset_condition(platform, platforms)})" for platform in platforms)
    return (WORKFLOW.replace("NOT_CONFIGURED_TOKEN", not_configured)
            .replace("NOTICE_STEPS_TOKEN", "".join(_notice_step(platform, platforms) for platform in platforms))
            .replace("BUILD_JOBS_TOKEN", "".join(_build_job(platform, platforms) for platform in platforms)))


def platform_for_preset(preset: str, target_triple: Optional[str] = None) -> str:
    """Map a project's native preset to its CI platform.

    macOS uses ``target_triple`` when a selected SDK supplied one, else this host's architecture.
    """
    if preset.startswith("linux-"):
        return "linux-x64"
    from .native import target_for_profile

    triple = target_triple or target_for_profile(preset)
    platforms = {"arm64-apple-darwin": "macos-arm64", "x86_64-apple-darwin": "macos-x64"}
    if triple not in platforms:
        raise ToolingError(INVALID_PROJECT, f"unsupported macOS CI target {triple!r}")
    return platforms[triple]


def find_git_root(path: Path) -> Optional[Path]:
    """Return the nearest directory at or above ``path`` that holds a ``.git`` entry, if any.

    ``path`` need not exist; the search starts at its nearest existing ancestor.
    A ``.git`` file (linked worktree or submodule) counts as a work tree root.
    The result has symbolic links resolved.
    """
    current = Path(path).resolve()
    while current.exists() is False and current.parent != current:
        current = current.parent
    for candidate in (current, *current.parents):
        if (candidate / ".git").exists() or (candidate / ".git").is_symlink():
            return candidate
    return None


def require_workflow_root(project_dir: Path) -> None:
    """Refuse a project that GitHub would not read workflows from.

    A project at a Git work tree root, or outside any work tree, is accepted.
    """
    project_dir = Path(project_dir).resolve()
    root = find_git_root(project_dir)
    if root is not None and root != project_dir:
        raise ToolingError(
            INVALID_PROJECT,
            f"the project is inside the Git repository at {root}; GitHub runs workflows only from "
            f"the repository root's .github/workflows, so a project workflow would never run. Add a "
            f"workflow at the repository root yourself, or move the project into its own repository",
        )


def require_tools_ref(tools_ref: Optional[str]) -> str:
    if tools_ref is None or _TOOLS_REF_RE.fullmatch(tools_ref) is None:
        raise ToolingError(INVALID_PROJECT, "CI setup requires --tools-ref <40-character Ludus commit>")
    return tools_ref


def validate_creation_ci(destination: Path, provider: Optional[str], tools_ref: Optional[str]) -> None:
    """Check New Project CI options before any engine preparation or staging."""
    if provider is None:
        if tools_ref is not None:
            raise ToolingError(INVALID_PROJECT, "--tools-ref requires --ci")
        return
    if provider not in CI_PROVIDERS:
        raise ToolingError(INVALID_PROJECT, f"unsupported CI provider {provider!r}")
    require_tools_ref(tools_ref)
    require_workflow_root(destination)


def tooling_checkout_ref(tooling_root: Path) -> str:
    """Return the commit checked out in a trusted Ludus tooling checkout, for ``--tools-ref``."""
    env = {key: value for key, value in os.environ.items() if key != "BUTLER_API_KEY"}
    result = subprocess.run(["git", "-C", str(tooling_root), "rev-parse", "HEAD"],
                            env=env, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise ToolingError(INVALID_PROJECT, f"cannot read the Ludus tooling commit at {tooling_root}")
    return require_tools_ref(result.stdout.strip())


def ci_files(platforms: Union[str, Sequence[str]], tools_ref: str) -> list[TemplateFile]:
    """Return the generated CI workflow for one or more platforms and its pinned tools revision."""
    platforms = (platforms,) if isinstance(platforms, str) else tuple(platforms)
    return [TemplateFile(WORKFLOW_RELPATH, workflow_text(*platforms)),
            TemplateFile(workflow_steps.TOOLS_REVISION_RELPATH, require_tools_ref(tools_ref) + "\n")]


def describe_repository(project_dir: Path) -> str:
    """Return a one-line note on whether pushing this project will run the workflow."""
    root = find_git_root(project_dir)
    if root is None:
        return "Not a Git repository yet: initialize Git and push the project to GitHub to run the workflow."
    url = _origin_url(root)
    if url is None:
        return "No origin remote: push this repository to GitHub to run the workflow."
    if re.match(r"(https://|ssh://git@|git@)github\.com[:/]", url) is None:
        return "The origin remote is not on github.com; the workflow runs only on GitHub Actions."
    return "The workflow runs on GitHub Actions after you commit and push it."


def _origin_url(root: Path) -> Optional[str]:
    git = root / ".git"
    if git.is_dir() is False:
        return None  # Linked worktrees keep remotes elsewhere; report no remote.
    try:
        text = (git / "config").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    section = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            section = stripped == '[remote "origin"]'
        elif section is True and stripped.startswith("url"):
            key, _, value = stripped.partition("=")
            if key.strip() == "url":
                return value.strip()
    return None


def setup_ci(project: Path, *, provider: str = "github", platform: Union[str, Sequence[str], None] = None,
             tools_ref: Optional[str] = None) -> list[str]:
    """Add the CI workflow to an existing version-2 CMake project; return the new files.

    ``platform`` names one native platform or several; each gets its own build
    job. Without it, the project's preset selects one platform.

    Never overwrites: an existing workflow fails with ``Conflict``. An existing
    ``config/ludus-tools-revision.txt`` naming the same commit is reused; a
    different commit is a ``Conflict``. Failure leaves no new files.
    """
    if provider not in CI_PROVIDERS:
        raise ToolingError(INVALID_PROJECT, f"unsupported CI provider {provider!r}")
    tools_ref = require_tools_ref(tools_ref)
    paths = operations.locate_project(project)
    root = paths.project_dir.resolve()
    model = descriptor.parse_descriptor_file(paths.descriptor_path)
    if model.version != 2 or model.provider != "cmake" or model.engine is None:
        raise ToolingError(INVALID_PROJECT, "CI setup requires a saved version-2 CMake project")
    if model.source_dir != ".":
        raise ToolingError(INVALID_PROJECT, "CI setup currently requires source_dir '.'")
    require_workflow_root(root)
    files = ci_files(platform or platform_for_preset(model.preset), tools_ref)
    if workflow_steps.has_tools_revision(root, tools_ref) is True:
        files = [file for file in files if file.relpath != workflow_steps.TOOLS_REVISION_RELPATH]
    generated: list[Path] = []
    with tempfile.TemporaryDirectory(prefix=".ci-setup-", dir=root) as temporary:
        stage = Path(temporary)
        for file in files:
            path = root / file.relpath
            if path.exists() or path.is_symlink():
                raise ToolingError(CONFLICT, f"CI setup refuses to overwrite {file.relpath}")
            staged = stage / file.relpath
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_text(file.content, encoding="utf-8")
        try:
            for file in files:
                path = root / file.relpath
                path.parent.mkdir(parents=True, exist_ok=True)
                os.link(stage / file.relpath, path)  # no-replace, including races
                generated.append(path)
        except OSError:
            for path in generated:
                path.unlink(missing_ok=True)
            raise
    return [path.relative_to(root).as_posix() for path in generated]
