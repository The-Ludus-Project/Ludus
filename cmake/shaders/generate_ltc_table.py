#!/usr/bin/env python3
"""Generate the renderer's embedded LTC table source from the checked-in binary.

tools/ltc-fit writes modules/graphics/renderer/data/ltc_table.bin, little-endian
float32 values in entries of four, and shaders/ltc_table_layout.h, whose
LUDUS_LTC_TABLE_* counts this script reads to validate the binary's size. The
output defines internal::LTC_TABLE (src/internal/ltc_table_data.h) with exact
hexadecimal float literals. See docs/development/ltc-table.md.
"""

import argparse
import re
import struct
import sys
from pathlib import Path

ENTRY_FLOATS = 4
FLOAT_BYTES = 4
COUNTS = ("ROUGHNESS_COUNT", "VIEW_COUNT", "FRESNEL_COUNT")


def read_counts(layout):
    text = Path(layout).read_text(encoding="utf-8")
    counts = {}
    for name in COUNTS:
        match = re.search(r"^#define LUDUS_LTC_TABLE_" + name + r" (\d+)$", text, re.MULTILINE)
        if match is None:
            sys.exit(f"generate_ltc_table: {layout} does not define LUDUS_LTC_TABLE_{name}")
        counts[name] = int(match.group(1))
    return counts


def literal(value):
    if value != value or value in (float("inf"), float("-inf")):
        sys.exit("generate_ltc_table: the table holds a nonfinite value")
    return float.hex(value) + "F" if value != 0.0 else "0.0F"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", required=True)
    parser.add_argument("--layout", required=True)
    parser.add_argument("--output", required=True)
    options = parser.parse_args()
    counts = read_counts(options.layout)
    slice_entries = counts["ROUGHNESS_COUNT"] * counts["VIEW_COUNT"]
    entry_count = slice_entries * (counts["FRESNEL_COUNT"] + 1)
    data = Path(options.table).read_bytes()
    expected = entry_count * ENTRY_FLOATS * FLOAT_BYTES
    if len(data) != expected:
        sys.exit(f"generate_ltc_table: {options.table} has {len(data)} bytes, the layout needs {expected}")
    values = struct.unpack("<" + "f" * (len(data) // FLOAT_BYTES), data)
    lines = [
        "// Generated by cmake/shaders/generate_ltc_table.py from data/ltc_table.bin; do not edit.",
        '#include "internal/ltc_table_data.h"',
        "",
        "namespace ludus::graphics::renderer::internal",
        "{",
        "const LtcTable LTC_TABLE{{",
    ]
    for index in range(entry_count):
        entry = values[index * ENTRY_FLOATS:(index + 1) * ENTRY_FLOATS]
        lines.append("    {" + ", ".join(literal(value) for value in entry) + "},")
    lines += ["}};", "} // namespace ludus::graphics::renderer::internal", ""]
    output = Path(options.output)
    text = "\n".join(lines)
    if output.exists() is False or output.read_text(encoding="utf-8") != text:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
