#!/usr/bin/env python3
"""Generate the renderer's embedded GGX albedo table source from the checked-in binary.

tools/ggx-albedo/generate_ggx_albedo_table.py writes modules/graphics/renderer/data/ggx_albedo_table.bin,
little-endian float32 values. shaders/ggx_albedo_table_layout.h defines their count, which this script reads to
validate the binary's size. The output defines internal::GGX_ALBEDO_TABLE (src/internal/ggx_albedo_table.h) with
exact hexadecimal float literals. See docs/architecture/renderer-systems.md#multiple-scattering-ggx-profile.
"""

import argparse
import re
import struct
import sys
from pathlib import Path

FLOAT_BYTES = 4
VALUES_PER_LINE = 4
COUNTS = ("ROUGHNESS_COUNT", "VIEW_COUNT")


def read_float_count(layout):
    text = Path(layout).read_text(encoding="utf-8")
    counts = {}
    for name in COUNTS:
        match = re.search(r"^#define LUDUS_GGX_ALBEDO_TABLE_" + name + r" (\d+)$", text, re.MULTILINE)
        if match is None:
            sys.exit(f"generate_ggx_albedo_table: {layout} does not define LUDUS_GGX_ALBEDO_TABLE_{name}")
        counts[name] = int(match.group(1))
    return counts["ROUGHNESS_COUNT"] * counts["VIEW_COUNT"] + counts["ROUGHNESS_COUNT"]


def literal(value):
    if value != value or value in (float("inf"), float("-inf")):
        sys.exit("generate_ggx_albedo_table: the table holds a nonfinite value")
    return float.hex(value) + "F" if value != 0.0 else "0.0F"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", required=True)
    parser.add_argument("--layout", required=True)
    parser.add_argument("--output", required=True)
    options = parser.parse_args()
    count = read_float_count(options.layout)
    data = Path(options.table).read_bytes()
    if len(data) != count * FLOAT_BYTES:
        sys.exit(f"generate_ggx_albedo_table: {options.table} has {len(data)} bytes, the layout needs "
                 f"{count * FLOAT_BYTES}")
    values = struct.unpack("<" + "f" * count, data)
    lines = [
        "// Generated by cmake/shaders/generate_ggx_albedo_table.py from data/ggx_albedo_table.bin; do not edit.",
        '#include "internal/ggx_albedo_table.h"',
        "",
        "namespace ludus::graphics::renderer::internal",
        "{",
        "const GgxAlbedoTable GGX_ALBEDO_TABLE{{",
    ]
    for first in range(0, count, VALUES_PER_LINE):
        lines.append("    " + ", ".join(literal(value) for value in values[first:first + VALUES_PER_LINE]) + ",")
    lines += ["}};", "} // namespace ludus::graphics::renderer::internal", ""]
    output = Path(options.output)
    text = "\n".join(lines)
    if output.exists() is False or output.read_text(encoding="utf-8") != text:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
