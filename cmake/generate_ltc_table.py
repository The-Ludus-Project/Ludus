#!/usr/bin/env python3
"""Generate the renderer's embedded LTC table source from the checked-in binary.

The binary is little-endian float32: every transform entry (four values), then every
albedo entry (two values); see modules/graphics/renderer/include/ludus/graphics/renderer/ltc_table.hpp.
The provenance JSON beside it records the layout this script validates. Values are written
as exact hexadecimal float literals.
"""

import argparse
import json
import struct
import sys
from pathlib import Path

TRANSFORM_FLOATS = 4
ALBEDO_FLOATS = 2


def literal(value):
    if value != value or value in (float("inf"), float("-inf")):
        raise ValueError("nonfinite table value")
    return float.hex(value) + "F" if value != 0.0 else "0.0F"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", required=True)
    parser.add_argument("--provenance", required=True)
    parser.add_argument("--output", required=True)
    options = parser.parse_args()
    provenance = json.loads(Path(options.provenance).read_text(encoding="utf-8"))
    data = Path(options.table).read_bytes()
    transforms = provenance["roughness_count"] * provenance["inclination_count"] * provenance["fresnel_count"]
    albedo = provenance["roughness_count"] * provenance["inclination_count"]
    expected = (transforms * TRANSFORM_FLOATS + albedo * ALBEDO_FLOATS) * 4
    if len(data) != expected or provenance["bytes"] != expected:
        sys.exit(f"generate_ltc_table: {options.table} has {len(data)} bytes, expected {expected}")
    values = struct.unpack("<" + "f" * (len(data) // 4), data)
    lines = [
        "// Generated by cmake/generate_ltc_table.py from ggx_ltc_table.bin; do not edit.",
        '#include "internal/ltc_table_data.h"',
        "",
        "namespace ludus::graphics::renderer::internal",
        "{",
        "const LtcTableEntry LTC_TABLE_TRANSFORMS[LTC_TABLE_TRANSFORM_COUNT] = {",
    ]
    for index in range(transforms):
        entry = values[index * TRANSFORM_FLOATS:(index + 1) * TRANSFORM_FLOATS]
        lines.append("    {" + ", ".join(literal(value) for value in entry) + "},")
    lines += ["};", "const LtcAlbedoEntry LTC_TABLE_ALBEDO[LTC_TABLE_ALBEDO_COUNT] = {"]
    base = transforms * TRANSFORM_FLOATS
    for index in range(albedo):
        entry = values[base + index * ALBEDO_FLOATS:base + (index + 1) * ALBEDO_FLOATS]
        lines.append("    {" + ", ".join(literal(value) for value in entry) + "},")
    lines += ["};", "} // namespace ludus::graphics::renderer::internal", ""]
    output = Path(options.output)
    text = "\n".join(lines)
    if output.exists() is False or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
